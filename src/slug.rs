/// The combining-mark blocks Latin text carries: diacritics with their extension and supplement, marks for symbols
/// and half marks.
const MARKS: &[(u32, u32)] = &[(0x300, 0x36F), (0x1AB0, 0x1AFF), (0x1DC0, 0x1DFF), (0x20D0, 0x20FF), (0xFE20, 0xFE2F)];

fn folded(c: char, out: &mut String) {
    let code = c as u32;
    if code < 0x80 {
        out.push(c.to_ascii_lowercase());
        return;
    }
    if MARKS.iter().any(|&(from, to)| (from..=to).contains(&code)) {
        return;
    }
    let at = FOLDS.partition_point(|&(first, _, _)| first <= code);
    if let Some(&(first, len, text)) = at.checked_sub(1).map(|i| &FOLDS[i]) {
        if code < first + len {
            if len == 1 {
                out.push_str(&text.to_ascii_lowercase());
            } else {
                // a run only ever maps single characters onto consecutive ASCII ones
                out.push((text.as_bytes()[0] + (code - first) as u8).to_ascii_lowercase() as char);
            }
            return;
        }
    }
    out.push(c);
}

/// The slug words of `text`, empty when none of its characters yield a letter or digit.
pub fn slug_words(text: &str) -> String {
    let mut ascii = String::new();
    text.chars().for_each(|c| folded(c, &mut ascii));
    let mut slug = String::new();
    let mut dash = false;
    for c in ascii.chars() {
        if c.is_ascii_lowercase() || c.is_ascii_digit() {
            if dash && !slug.is_empty() {
                slug.push('-');
            }
            dash = false;
            slug.push(c);
        } else {
            dash = true;
        }
    }
    slug
}

#[cfg(test)]
mod tests {
    use super::slug_words;

    #[test]
    fn transliterates_accented_letters() {
        assert_eq!(slug_words("ünï"), "uni");
        assert_eq!(slug_words("Café Crème"), "cafe-creme");
        assert_eq!(slug_words("Fix: SSO login (My App)!"), "fix-sso-login-my-app");
    }

    #[test]
    fn folds_compatibility_forms() {
        assert_eq!(slug_words("ＦＵＬＬ ｗｉｄｔｈ ９"), "full-width-9");
        assert_eq!(slug_words("ﬁle №"), "file-no");
        assert_eq!(slug_words("𝐁𝐨𝐥𝐝 ² ①"), "bold-2-1");
        assert_eq!(slug_words("İstanbul"), "istanbul");
    }

    #[test]
    fn decomposed_input_loses_its_marks_too() {
        assert_eq!(slug_words("cafe\u{301}"), "cafe");
        assert_eq!(slug_words("a\u{301}b"), "ab");
    }

    #[test]
    fn letters_nfkd_leaves_alone_are_separators() {
        assert_eq!(slug_words("straße"), "stra-e");
        assert_eq!(slug_words("日本語 タイトル"), "");
        assert_eq!(slug_words("日本語 v2"), "v2");
        assert_eq!(slug_words(""), "");
    }
}
